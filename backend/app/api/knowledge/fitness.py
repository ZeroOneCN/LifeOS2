def match_keyword(name: str, table: dict) -> tuple[str | None, object]:
    """在表内按关键词匹配，返回 (命中的key, 命中值)。中文按包含匹配。"""
    if not name:
        return None, None
    for key, value in table.items():
        if key and key in name:
            return key, value
    # 英文/拼音兜底：直接精确匹配
    direct = table.get(name.strip().lower())
    return (name.strip().lower(), direct) if direct is not None else (None, None)


def estimate_nutrition(food_name: str, weight_g: float) -> dict:
    """根据食物名称与重量推算营养成分。"""
    key, per100 = match_keyword(food_name, FOOD_NUTRITION)
    if per100 is None:
        matched = False
        per100 = (116, 2.6, 25.9, 0.3)  # 未知食物按米饭近似
    else:
        matched = True
    cal, pro, carb, fat = per100
    factor = weight_g / 100.0
    return {
        "food_name": food_name,
        "matched": matched,
        "matched_key": key,
        "weight_g": round(weight_g, 1),
        "calories": round(cal * factor, 1),
        "protein": round(pro * factor, 1),
        "carbs": round(carb * factor, 1),
        "fat": round(fat * factor, 1),
    }


def estimate_calories(exercise_type: str, duration_min: int, weight_kg: float = 65.0) -> tuple[float, str | None]:
    """根据运动类型与时长推算消耗热量(千卡)。返回 (热量, 命中的MET键)。"""
    key, met = match_keyword(exercise_type, EXERCISE_MET)
    if met is None:
        return 0.0, None
    return round(met * weight_kg * duration_min / 60, 1), key