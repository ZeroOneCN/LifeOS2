def _seed() -> int:
    """以「当天序号 * 24 + 当前小时」为种子，保证同一天同一小时返回同一句，
    跨小时自动切换，实现每小时更新一句话。"""
    now = datetime.now()
    hour_of_year = now.timetuple().tm_yday * 24 + now.hour
    digest = sha256(f"rainbow:{hour_of_year}".encode()).digest()
    return int.from_bytes(digest[:4], "big")


@router.get("/rainbow")
def rainbow() -> dict[str, str | int]:
    """返回一句彩虹屁。按小时稳定切换，同小时所有请求返回同一句。"""
    seq = _seed() % len(_RAINBOW)
    now = datetime.now()
    return {
        "content": _RAINBOW[seq],
        "sequence_no": seq,
        "hour": now.hour,
        "updated_at": now.strftime("%Y-%m-%d %H:%M:%S"),
    }